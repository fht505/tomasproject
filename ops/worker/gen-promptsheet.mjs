#!/usr/bin/env node
// Build a Gemini-ready batch sheet: every design prompt, in order, with the
// technical directives that model actually honours.
//
//   node ops.mjs sheet
//
// The prompts in PROMPTS.md were written for the ChatGPT app, which takes no
// size or ratio arguments. Nano Banana 2 does, and each product needs a
// different one — a candle label is landscape 3:2, a tee front is portrait
// 4:5, a mug wrap is 21:9. Getting that right in the prompt avoids a crop or a
// regeneration per design, which is the operator's time.
//
// It also appends the transparency instruction ONLY where it matters. Apparel
// prints on fabric and needs alpha; a mug and a candle label are full-bleed
// wraps and do not. Asking for transparency on a wrap wastes a generation.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { PATHS } from './config.mjs';
import { TYPE_TO_KEY } from './products.mjs';

// Closest supported Gemini aspect ratio to each real print area, plus whether
// the print sits on fabric. Print areas measured from the live Printify
// catalog — see BLUEPRINT_SEARCH in stage.mjs.
const SPEC = {
  candle: { ratio: '3:2', alpha: false, area: '900x600 label' },
  tee: { ratio: '4:5', alpha: true, area: '2767x3362 front' },
  sweatshirt: { ratio: '4:5', alpha: true, area: '2976x3398 front' },
  mug: { ratio: '21:9', alpha: false, area: '2700x1120 wrap' },
  tote: { ratio: '4:5', alpha: true, area: '3000x3600 front' },
};

if (!existsSync(PATHS.listings)) {
  console.error('no BATCH-01.listings.json — run: node ops.mjs listings');
  process.exit(1);
}
const { listings } = JSON.parse(readFileSync(PATHS.listings, 'utf8'));

const promptsPath = join(PATHS.ops, 'PROMPTS.md');
const md = existsSync(promptsPath) ? readFileSync(promptsPath, 'utf8') : '';
// Line endings are CRLF on Windows after checkout, so the blockquote matcher
// has to tolerate \r explicitly. It did not, which silently truncated C1 and C2
// to their first line — the entire creative description was dropped and nobody
// noticed until the generated image came back as something else.
const promptFor = (code) => {
  const m = md.match(new RegExp(`\\*\\*${code}\\*\\*[^\\S\\r\\n]*\\r?\\n((?:>[^\\r\\n]*\\r?\\n?)+)`));
  if (!m) return null;
  let text = m[1].split(/\r?\n/).map(l => l.replace(/^>\s?/, '')).join(' ').replace(/\s+/g, ' ').trim();

  // The directive block below owns the background instruction. Leaving the
  // original "isolated on transparent background" in place made the prompt
  // argue with itself — and "transparent" is precisely the word that made the
  // model draw a checkerboard.
  text = text
    .replace(/,?\s*isolated on (a )?(fully )?transparent background/gi, '')
    .replace(/,?\s*on (a )?(fully )?transparent background/gi, '')
    .replace(/\s*,\s*,/g, ',')
    .replace(/\s+/g, ' ')
    .replace(/^\s*,\s*/, '')
    .trim();
  return text;
};

// one row per ART FILE, not per listing — the C-series reuses A/B artwork
const byArt = new Map();
for (const l of listings) {
  const key = TYPE_TO_KEY[l.product];
  const cur = byArt.get(l.art_file);
  if (!cur) byArt.set(l.art_file, { file: l.art_file, uses: [l.code], keys: new Set([key]), phrase: l.phrase });
  else { cur.uses.push(l.code); cur.keys.add(key); }
}

const all = [...byArt.values()].sort((a, b) => {
  const k = (f) => [f.file[0], parseInt(f.file.slice(1), 10) || 0];
  const [la, na] = k(a), [lb, nb] = k(b);
  return la === lb ? na - nb : la < lb ? -1 : 1;
});

// `--test` emits one of each product shape instead of all 34. The first batch
// cost an hour before we learned the directives were wrong; three images
// answer the same question for the price of three.
const testMode = process.argv.includes('--test');
const order = testMode
  ? ['candle', 'tee', 'mug'].map(k => all.find(a => [...a.keys][0] === k)).filter(Boolean)
  : all;

const conflicts = [];
const out = [
  testMode ? '# BATCH-01 — TEST BATCH (3 images)' : '# BATCH-01 — Gemini batch sheet',
  '',
  testMode
    ? 'One candle, one tee, one mug — enough to prove the directives work before committing to the full 34. Generate these three, then hand me the folder.'
    : `${order.length} designs. Work top to bottom. Generated by \`node ops.mjs sheet\` — do not hand-edit.`,
  '',
  '> **What changed after batch 1.** Asking for a "transparent background" made the',
  '> model draw a picture of a checkerboard, which cannot be keyed out. It now asks',
  '> for solid white, which `art key` removes cleanly. And every candle label',
  '> invented a net weight (8oz and 12oz against a real 9oz product), a burn time,',
  '> and "hand-poured" claims that nothing asked for — so the prompts now forbid any',
  '> text beyond the phrase itself.',
  '',
  '## How to run this',
  '',
  '1. In Gemini, set the model to **3.1 Pro / Nano Banana 2** and output to **4K** if the option is offered.',
  '2. Paste a prompt. The aspect ratio and background directive are already in it.',
  '3. **Check the spelling letter by letter before saving.** This is the one defect nothing downstream catches — a misspelled print is a refund and a bad review.',
  '4. Save the image anywhere. The filename does not matter.',
  '5. When a batch is done, drop them all in one folder and tell me where.',
  '',
  '> Why 4K: the tee print area is 2767x3362 and the tote is 3000x3600. At 4096px every product **downscales**, so nothing is ever upscaled and no detail is invented.',
  '',
  '---',
  '',
];

for (const [i, art] of order.entries()) {
  const key = [...art.keys][0];
  const spec = SPEC[key] || SPEC.tee;
  const base = promptFor(art.file.replace(/\.png$/i, ''));
  const usedBy = art.uses.length > 1 ? ` — used by ${art.uses.join(', ')}` : '';

  out.push(`## ${i + 1}/${order.length} · ${art.file.replace(/\.png$/i, '')}${usedBy}`);
  out.push('');
  out.push(`**Printed text:** ${art.phrase ? `\`${art.phrase}\`` : '_see prompt_'}  `);
  out.push(`**Print area:** ${spec.area} · **ratio:** ${spec.ratio}`);
  out.push('');

  if (!base) {
    out.push('> ⚠️ No prompt found for this code in ops/PROMPTS.md.');
    out.push('');
    continue;
  }

  // A prompt that says "portrait" against a landscape print area fights the
  // ratio directive and the model picks one. All 12 candle prompts said
  // "portrait rectangle" while the real print area is 900x600 landscape —
  // written before we had measured it. Catch the contradiction rather than
  // shipping 34 prompts that argue with themselves.
  const [rw, rh] = spec.ratio.split(':').map(Number);
  const wantsLandscape = rw > rh;
  const saysPortrait = /\bportrait\b/i.test(base);
  const saysLandscape = /\blandscape\b/i.test(base);
  if ((wantsLandscape && saysPortrait) || (!wantsLandscape && saysLandscape)) {
    conflicts.push(`${art.file.replace(/\.png$/i, '')}: prompt says ${saysPortrait ? 'portrait' : 'landscape'} but the ${spec.area} print area is ${wantsLandscape ? 'landscape' : 'portrait'} (${spec.ratio})`);
  }
  // The word "transparent" is what made the model draw a checkerboard. If it
  // survived the strip above, the prompt will fight its own directive.
  if (/transparent/i.test(base)) {
    conflicts.push(`${art.file.replace(/\.png$/i, '')}: prompt still says "transparent" — it will contradict the solid-white directive and may produce a checkerboard`);
  }
  // A prompt whose creative description was truncated is worse than useless.
  if (base.split(/\s+/).length < 12) {
    conflicts.push(`${art.file.replace(/\.png$/i, '')}: prompt is only ${base.split(/\s+/).length} words — the description was probably truncated when parsed from PROMPTS.md`);
  }

  // Every clause here exists because its absence produced a specific failure
  // in the first batch. Positive instructions alone were not enough — the
  // model fills any gap you leave it.
  // Some designs legitimately carry secondary text — C1's prescription parody
  // wants a small "REFILL AS NEEDED" line. Pull every quoted string out of the
  // creative description so the allow-list matches the brief instead of
  // contradicting it. Forbidding all but the headline would have made the model
  // choose between two instructions in the same prompt.
  const quoted = [...base.matchAll(/"([^"]{2,60})"/g)].map(m => m[1].trim());
  const allowed = [...new Set([
    ...(art.phrase ? [art.phrase.toUpperCase()] : []),
    ...quoted.map(q => q.toUpperCase()),
  ])];
  const exact = allowed.length > 1
    ? allowed.map(t => `"${t}"`).join(' and ')
    : `"${allowed[0] || art.phrase || ''}"`;
  const directives = [
    `Aspect ratio ${spec.ratio}.`,
    'Render at the highest resolution available.',
    // "transparent background" made a JPEG-only model DRAW a checkerboard,
    // which cannot be keyed out because it is mid-grey rather than white.
    spec.alpha
      ? 'Put the artwork on a SOLID PURE WHITE background (#FFFFFF), filling the frame edge to edge. Do NOT render a transparency checkerboard, grey squares, or any grid pattern. No mockup, no garment, no shadow, no frame, no border.'
      : 'Flat artwork only — no product mockup, no scene, no hands, no shadow.',
    // The candle labels invented net weights (8oz and 12oz, against a real 9oz
    // product), burn times, scent numbers and "hand-poured" claims. Nothing
    // asked for them; the model supplied what a real label usually carries.
    `The ONLY text anywhere in the image must be ${exact}${allowed.length > 1 ? ' — and nothing else' : ''}, spelled letter for letter.`,
    'Do NOT add any other words, numbers, net weight, volume, ounces, grams, burn time, scent numbers, dates, website, brand name, taglines, or product claims such as "hand-poured" or "small batch".',
    'Text must be crisp and legible at full size.',
  ].join(' ');

  out.push('```');
  out.push(`${base} ${directives}`);
  out.push('```');
  out.push('');
}

out.push('---', '', '## When the batch is done', '',
  'Tell me the folder. I will, for every file:', '',
  '- read it and **verify the printed text letter by letter** against the phrase above',
  '- check resolution, aspect and transparency against the real print area',
  '- key out a white background if the model ignored the transparency directive',
  '- file it under the right code and build the print master',
  '',
  'Anything that fails comes back to you with the specific reason and the prompt to re-run.', '');

const dest = join(PATHS.ops, testMode ? 'BATCH-SHEET-TEST.md' : 'BATCH-SHEET.md');
writeFileSync(dest, out.join('\n'));
console.log(`\n  wrote ${order.length} prompts -> ${dest}`);
console.log(`  ratios: ${[...new Set(order.map(a => SPEC[[...a.keys][0]]?.ratio))].join(', ')}`);
console.log(`  ${order.filter(a => SPEC[[...a.keys][0]]?.alpha).length} need a transparent background`);

if (conflicts.length) {
  console.log(`\n  ${conflicts.length} ORIENTATION CONFLICT(S) — the prompt argues with the print area:`);
  for (const c of conflicts) console.log(`    ${c}`);
  console.log('  Fix the wording in ops/PROMPTS.md, then re-run.\n');
  process.exitCode = 1;
} else {
  console.log('  no orientation conflicts\n');
}
